#!/usr/bin/env node
// 手机端复用桌面 chat 执行 UI 的样式接缝之二：桌面 markdown.css 的**位置改写**。
//
// 桌面 `app-web/styles/markdown.css` 里有四条
//     @source "../../node_modules/<包>/dist/..."（Streamdown 的四份包）
// Tailwind 是照**这个文件自己所在的位置**去找这些包的，也就是桌面仓库的 node_modules。
// CI 里桌面只 checkout 源码、不装依赖（两个仓库并排 checkout，只有手机跑 npm ci），
// 这四条一条也扫不到——于是 Streamdown 用的那批 Tailwind 工具类在包里根本不存在：
// 表格（bg-muted / divide-y / overflow-x-auto / max-w-full）、代码块（rounded-md /
// text-muted-foreground）整片没有样式。**本地一点毛病看不出来**（本地桌面仓库装着依赖，
// 扫得到），第 51 次构建发出去的包就是这么坏的：手机上表格列错位、代码块没底色。
//
// 做法：把桌面那份**原样复制**到手机仓库，只把 @source 的起点从桌面的 node_modules
// 改成手机自己的（两份 package.json 钉的是同一批版本，见 vite.config.js 的
// desktopPackages；构建产物由 scripts/verify-bundled-styles.mjs 在 CI 上兜底核验）。
// 再由 vite 的 alias 把桌面那个路径指到这份副本（vite.config.js）——全树只编译一份，
// 两份的话 theme / preflight / .haish-markdown 规则会各来一遍。
//
// 生成物 src/desktop-markdown.generated.css 不进版本库（.gitignore），prebuild/predev 重生成。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, '..');
const sourceFile = path.resolve(projectRoot, '..', 'haish-agent', 'app-web', 'styles', 'markdown.css');
const outputFile = path.resolve(projectRoot, 'src', 'desktop-markdown.generated.css');

/** 桌面那份里的四条 @source 都指向桌面仓库的 node_modules。 */
const DESKTOP_PREFIX = '@source "../../node_modules/';
/** 副本放在 src/ 下，node_modules 就在上一级。 */
const MOBILE_PREFIX = '@source "../node_modules/';
/** 应该有几条（Streamdown 的四份包）。桌面少一条就是它改了结构，这里要停下来看。 */
const EXPECTED_SOURCES = 4;

/** 纯函数：把桌面那份 markdown.css 改成在手机仓库里也能扫到包的样子。 */
export function rewriteDesktopMarkdown(source) {
  const count = source.split(DESKTOP_PREFIX).length - 1;
  if (count < EXPECTED_SOURCES) {
    throw new Error(
      `桌面 markdown.css 里指向 node_modules 的 @source 只剩 ${count} 条（期望 ${EXPECTED_SOURCES} 条）：`
      + '桌面的 markdown 样式结构变了，先看 app-web/styles/markdown.css 里的 @source 现在长什么样，'
      + '再更新本脚本的 DESKTOP_PREFIX。',
    );
  }
  return source.split(DESKTOP_PREFIX).join(MOBILE_PREFIX);
}

function header(source) {
  return [
    '/* GENERATED by scripts/gen-desktop-markdown-css.mjs — 不要手工编辑。',
    ` * 来源：${path.relative(projectRoot, sourceFile)}（逐字节复制，只改了 @source 的起点）。`,
    ' * 桌面那份的 @source 指向桌面仓库的 node_modules，CI 里那边没装依赖，Tailwind 扫不到',
    ' * Streamdown 的类名，表格 / 代码块的工具类会整段消失（本地的桌面仓库装着依赖，看不出来）。',
    ' * 这里指向手机自己的 node_modules；vite 的 alias 把桌面那个路径指到本文件。',
    ' */',
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (!fs.existsSync(sourceFile)) {
    console.error(`gen-desktop-markdown-css: 找不到桌面样式表 ${sourceFile}`);
    console.error('手机端复用桌面 chat UI，构建前需要 ../haish-agent 检出（CI 里由 workflow 检出 pin 的 ref）。');
    process.exit(1);
  }
  const source = fs.readFileSync(sourceFile, 'utf8');
  let rewritten;
  try {
    rewritten = rewriteDesktopMarkdown(source);
  } catch (error) {
    console.error(`gen-desktop-markdown-css: ${error.message}`);
    process.exit(1);
  }
  if (rewritten.includes('"../../node_modules/')) {
    console.error('gen-desktop-markdown-css: 改写后还有指向桌面 node_modules 的 @source，停止生成。');
    process.exit(1);
  }
  // 注释里不能出现 `*/`（会提前收尾），所以上面的 import 说明不写成通配写法。
  fs.writeFileSync(outputFile, `${header()}\n${rewritten}`, 'utf8');
  console.log(`gen-desktop-markdown-css: ${path.relative(projectRoot, outputFile)} ← ${path.relative(projectRoot, sourceFile)}`);
}
