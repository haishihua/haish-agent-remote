#!/usr/bin/env node
// 手机端复用桌面 chat 执行 UI 的样式接缝之一：把桌面 base.css 里**只与这些组件有关**的块摘出来。
//
// 为什么是「摘」而不是整份 @import：base.css 里除了我们要的 :root token、.ico-* 遮罩图标、
// portal-tooltip 样式，还有 html/body（overflow:hidden、Zpix 像素字体）、#root（100vw/100vh +
// 桌面底色）、:focus/:focus-visible（outline:none !important）这些全局规则——整份进来会把手机端的
// 滚动容器、字体和焦点环一起改掉，而这些正是前几版花力气修好的观感。
//
// 为什么是生成而不是手抄：token 数值和图标遮罩一旦在桌面侧改动，手抄的副本会静默漂移。
// 这里按**选择器**挑选（不是按行号），桌面重排文件也不会切坏；挑不到必需的块就直接让构建失败。
//
// 生成物 src/desktop-base.generated.css 不进版本库（.gitignore），由 npm 的 prebuild/predev 跑。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, '..');
const sourceFile = path.resolve(projectRoot, '..', 'haish-agent', 'app-web', 'styles', 'base.css');
const outputFile = path.resolve(projectRoot, 'src', 'desktop-base.generated.css');
const assetsDir = path.resolve(projectRoot, '..', 'haish-agent', 'app-web', 'assets');

/** 取哪些块：token + 图标 + tooltip。其余（html/body/#root/:focus/…）一律不要。 */
// 说明：.topbar-title / .td-title 那条标题字块跟这边无关（手机有自己的标题字），刻意不收。
const KEEP = [
  { name: ':root', test: (selector) => selector === ':root' },
  { name: 'svg', test: (selector) => selector === 'svg' },
  { name: '.ico 图标字形', test: (selector) => selector === '.ico' || selector.startsWith('.ico-') },
  { name: 'portal tooltip', test: (selector) => selector.startsWith('.portal-tooltip') || selector.startsWith('.app-tooltip-') },
];
/** 这些块必须留在外面，出现即说明切法失效（会把手机端全局观感改掉）。 */
const MUST_SKIP = [/^(\*|html|body|#root)\b/, /:focus/];

/** 按顶层 `{}` 切块：选择符 = 上一个块结束到 `{` 之间的文本（去注释），css = 整块原文。 */
function topLevelBlocks(source) {
  const blocks = [];
  let depth = 0;
  let cursor = 0;
  let index = 0;
  while (index < source.length) {
    const char = source[index];
    if (char === '/' && source[index + 1] === '*') {
      const end = source.indexOf('*/', index + 2);
      index = end < 0 ? source.length : end + 2;
      continue;
    }
    if (char === '{') {
      depth += 1;
      index += 1;
      continue;
    }
    if (char === '}') {
      depth -= 1;
      if (depth === 0) {
        const raw = source.slice(cursor, index + 1);
        cursor = index + 1;
        const selector = raw.slice(0, raw.indexOf('{'))
          .replace(/\/\*[\s\S]*?\*\//g, '')
          .replace(/\s+/g, ' ')
          .trim();
        // 块前的说明性注释不带进生成物（它们说的是桌面自己的结构）。
        const css = raw.replace(/^\s*(\/\*[\s\S]*?\*\/\s*)*/, '').trim();
        if (selector) blocks.push({ selector, css });
      }
      index += 1;
      continue;
    }
    index += 1;
  }
  return blocks;
}

function rewriteUrls(css) {
  return css.replace(/url\(\s*(['"]?)([^'")]+)\1\s*\)/g, (match, quote, target) => {
    if (/^(data:|https?:|#|\/\/)/i.test(target)) return match;
    const absolute = path.resolve(path.dirname(sourceFile), target);
    let relative = path.relative(path.dirname(outputFile), absolute).split(path.sep).join('/');
    if (!relative.startsWith('.')) relative = `./${relative}`;
    return `url("${relative}")`;
  });
}

if (!fs.existsSync(sourceFile)) {
  console.error(`gen-desktop-base-css: 找不到桌面样式表 ${sourceFile}`);
  console.error('手机端复用桌面 chat UI，构建前需要 ../haish-agent 检出（CI 里由 workflow 检出 pin 的 ref）。');
  process.exit(1);
}

const source = fs.readFileSync(sourceFile, 'utf8');
const blocks = topLevelBlocks(source);
const pieces = [];
const kept = new Set();
const keptSelectors = new Set();
const skipped = [];

for (const block of blocks) {
  const rule = KEEP.find((item) => item.test(block.selector));
  if (rule && !MUST_SKIP.some((pattern) => pattern.test(block.selector))) {
    pieces.push(block.css);
    kept.add(rule.name);
    keptSelectors.add(block.selector);
  } else {
    skipped.push(block.selector);
  }
}

// 摘出来的块里不能再夹带全局规则（选择器列表里混进 html/body 也要拦）。
const offenders = [...keptSelectors].filter((selector) => /^(\*|html|body|#root)(\b|,)/.test(selector));
if (offenders.length) {
  console.error('gen-desktop-base-css: 挑出来的块里混进了全局选择器，停止生成。');
  for (const selector of offenders) console.error(`  ${selector}`);
  process.exit(1);
}

const missing = KEEP.filter((rule) => !kept.has(rule.name)).map((rule) => rule.name);
if (missing.length) {
  console.error(`gen-desktop-base-css: 桌面 base.css 里找不到这些块：${missing.join('、')}`);
  console.error('桌面的样式结构变了——先看 app-web/styles/ 里它们搬到哪，再更新本脚本的 KEEP。');
  process.exit(1);
}

// 手机端 timeline 会用到的几个字形必须在场（少了就是「图标变空白」，构建期就该拦）。
for (const required of ['.ico', '.ico-browser', '.ico-terminal', '.ico-ask-user', '.portal-tooltip', ':root']) {
  if (!keptSelectors.has(required)) {
    console.error(`gen-desktop-base-css: 生成结果里缺少 ${required}（桌面可能改了图标类名）。`);
    process.exit(1);
  }
}

const header = [
  '/* GENERATED by scripts/gen-desktop-base-css.mjs — 不要手工编辑。',
  ` * 来源：${path.relative(projectRoot, sourceFile)}`,
  // 注释里不能出现 `*/`（会提前收尾），所以这里用「等」代掉通配写法。
  ` * 只摘了 ${[...kept].join('、')}；跳过的顶层块 ${skipped.length} 个（html/body/#root 等全局规则留在桌面侧）。`,
  ' */',
  '',
].join('\n');

fs.writeFileSync(outputFile, `${header}${rewriteUrls(pieces.join('\n\n'))}\n`, 'utf8');
console.log(`gen-desktop-base-css: ${path.relative(projectRoot, outputFile)} ← ${kept.size} 类块 / 跳过 ${skipped.length} 块`);
